    private static array $cache = [];

    /** @return array<int,int> byte value => width */
    public static function widths(string $fontKey): array
    {
        if (str_starts_with($fontKey, 'courier')) {
            return [];
        }
        $key = match ($fontKey) {
            'helveticaI' => 'helvetica',
            'helveticaBI' => 'helveticaB',
            default => $fontKey,
        };
        if (!isset(self::ASCII[$key])) {
            $key = 'helvetica';
        }
        if (!isset(self::$cache[$key])) {
            $values = array_map('intval', explode(' ', self::ASCII[$key]));
            self::$cache[$key] = array_combine(range(32, 32 + count($values) - 1), $values);
        }
        return self::$cache[$key];
    }

    public static function defaultWidth(string $fontKey): int
    {
        return match (true) {
            str_starts_with($fontKey, 'courier') => 600,
            str_starts_with($fontKey, 'times') => 500,
            default => 556,
        };
    }
